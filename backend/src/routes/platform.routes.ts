import { notificationsRouter } from '../modules/notifications/notifications.routes.js';
import { Router } from 'express';
import { requireAuth, requireCsrf, requireOrigin } from '../modules/auth/auth.middleware.js';
import { ApiError } from '../utils/ApiError.js';
import { pricingPublicRouter } from '../modules/pricing/pricing.public.routes.js';
import { caregiversPublicRouter } from '../modules/caregivers/caregivers.public.routes.js';
import { careRequestsPublicRouter } from '../modules/care-requests/care-requests.public.routes.js';
import { caregiversRouter } from '../modules/caregivers/caregivers.routes.js';
import { membershipRouter } from '../modules/membership/membership.routes.js';
import { careRequestsRouter } from '../modules/care-requests/care-requests.routes.js';
import { applicationsRouter } from '../modules/applications/applications.routes.js';
import { messagesRouter } from '../modules/messages/messages.routes.js';
import { savedCaregiversRouter } from '../modules/saved-caregivers/saved-caregivers.routes.js';
import { reviewsRouter } from '../modules/reviews/reviews.routes.js';
import { verificationsRouter } from '../modules/verifications/verifications.routes.js';
import { adminRouter } from '../modules/admin/admin.routes.js';
import { organisationsRouter } from '../modules/organisations/organisations.routes.js';
import { organisationsPublicRouter } from '../modules/organisations/organisations.public.routes.js';
import { packageToolsRouter } from '../modules/package-tools/package-tools.routes.js';
import { accountRouter } from '../modules/account/account.routes.js';
import { dashboardRouter } from '../modules/dashboard/dashboard.routes.js';
import { uploadsRouter, profilePhotosRouter } from '../modules/uploads/uploads.routes.js';
import { blogAdminRouter, blogPublicRouter } from '../modules/blog/blog.routes.js';
export const platformRouter = Router();
platformRouter.use(pricingPublicRouter);
platformRouter.use(caregiversPublicRouter);
platformRouter.use(careRequestsPublicRouter);
platformRouter.use(organisationsPublicRouter);
platformRouter.use(profilePhotosRouter);
platformRouter.use(blogPublicRouter);
platformRouter.use(requireAuth, (req, res, next) => {
  res.set('Cache-Control', 'no-store, private');
  if (req.auth!.user.role === 'CARE_SEEKER' && !req.auth!.user.profileComplete)
    throw new ApiError(403, 'Complete your profile before accessing the dashboard.');
  if (!['GET', 'HEAD'].includes(req.method))
    return requireOrigin(req, res, () => requireCsrf(req, res, next));
  next();
});
platformRouter.use(accountRouter);
platformRouter.use(uploadsRouter);
platformRouter.use(blogAdminRouter);
platformRouter.use(notificationsRouter);
platformRouter.use(dashboardRouter);
platformRouter.use(caregiversRouter);
platformRouter.use(membershipRouter);
platformRouter.use(careRequestsRouter);
platformRouter.use(applicationsRouter);
platformRouter.use(messagesRouter);
platformRouter.use(savedCaregiversRouter);
platformRouter.use(reviewsRouter);
platformRouter.use(verificationsRouter);
platformRouter.use(adminRouter);
platformRouter.use(organisationsRouter);
platformRouter.use(packageToolsRouter);
